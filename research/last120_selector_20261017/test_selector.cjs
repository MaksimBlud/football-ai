'use strict';
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const candidate=process.env.SELECTOR_HTML||path.join(__dirname,'index.html');
const html=fs.readFileSync(candidate,'utf8');
assert.match(html,/фактическ/);
const m=html.match(/<script>\s*([\s\S]*?)\s*<\/script>/);
assert.ok(m,'selector must contain a single inline script');
const code=m[1].replace(/setOptions\(\);render\(\);\s*$/,'');
assert.notEqual(code,m[1],'should strip only bootstrap, leaving functions intact');
const listeners={},elements={};
const document={getElementById(id){return elements[id] ||= {value:'',textContent:'',innerHTML:'',addEventListener(name,handler){listeners[id+':'+name]=handler},classList:{toggle(){},remove(){},add(){}}}}};
const saved={},localStorage={getItem(k){return saved[k]||null},setItem(k,v){saved[k]=v}};
const context=vm.createContext({document,localStorage,setTimeout(){},console,confirm(){return true}});
vm.runInContext(code,context,{filename:'index.html',timeout:10000});
vm.runInContext('setOptions=()=>{};render=()=>{};toast=()=>{}',context);
const ev=s=>vm.runInContext(s,context);
const n=ev('fixtures.length');
assert.ok(n>=52&&n<=400,'meaningful bounded schedule');
assert.equal(ev('fixtures.filter(f=>f.league==="РПЛ").length')>0,true);
const s=(league,h,a,verified=true)=>ev(`status({league:${JSON.stringify(league)},score85_home:${JSON.stringify(h)},score85_away:${JSON.stringify(a)},verified85:${verified}}).type`);
assert.equal(s('АПЛ','0','0'),'best');
assert.equal(s('Серия А','1','1'),'good');
assert.equal(s('АПЛ','3','0'),'bad');
assert.equal(s('РПЛ','0','0'),'hypothesis');
assert.equal(s('Unknown league','0','0'),'unsupported');
assert.equal(s('АПЛ','0','0',false),'pending');
assert.equal(ev('isCandidate({type:"hypothesis"})'),false,'RPL may not be silently validated');
assert.equal(ev('isCandidate({type:"best"})'),true);
assert.equal(ev('selectionList(false).length'),0,'no candidates before snapshots');
const header='league,date,time,home,away,round,score85_home,score85_away,verified85';
const imp=txt=>{document.getElementById('importText').value=header+'\n'+txt;listeners['importBtn:click']()};
imp('АПЛ,2026-12-12,12:00,Unit Test A,Unit Test B,20,0,0,true');
assert.equal(ev('fixtures.length'),n+1);
assert.equal(ev('selectionList(false).length'),1);
imp('АПЛ,2026-12-12,12:00,Unit Test A,Unit Test B,20,1,0,false');
assert.equal(ev('selectionList(false).length'),0,'change must invalidate old confirmation');
assert.equal(ev('fixtures.find(f=>f.home==="Unit Test A").verified85'),false);
imp('РПЛ,2026-12-12,15:00,Unit Test RPL,Unit Test Opp,20,1,1,true');
assert.equal(ev('selectionList(false).length'),0,'RPL must not enter validated export');
assert.equal(ev('selectionList(true).length'),1,'RPL hypothesis may be listed separately');
const before=ev('fixtures.length');
imp('АПЛ,2026-12-13,12:00,Atomic A,Atomic B,20,,,false\nАПЛ,2026-15-12,12:00,Atomic C,Atomic D,20,,,false');
assert.equal(ev('fixtures.length'),before,'invalid second row must roll back entire import');
imp('Другая лига,2026-12-20,18:00,Other A,Other B,20,0,0,true');
assert.equal(ev('selectionList(false).length'),0,'unknown league must fail closed');
console.log(`PASS ${n} fixtures; validated/RPL/unsupported classification; stale-score invalidation; atomic CSV import`);
