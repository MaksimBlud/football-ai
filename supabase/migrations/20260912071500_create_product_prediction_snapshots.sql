create table if not exists public.product_prediction_snapshots (
    id bigint generated by default as identity primary key,
    snapshot_schema_version text not null default 'product-prediction.v1',
    run_id text not null,
    generated_at_utc timestamptz not null,
    league text not null,
    event_id text,
    commence_time_utc timestamptz not null,
    match_date date not null,
    match_time text not null,
    home_team text not null,
    away_team text not null,
    home_team_model text not null,
    away_team_model text not null,
    prediction text,
    prediction_strength text,
    model_agreement boolean,
    home_probability double precision not null check (home_probability between 0 and 1),
    draw_probability double precision not null check (draw_probability between 0 and 1),
    away_probability double precision not null check (away_probability between 0 and 1),
    expected_home_goals double precision check (expected_home_goals is null or expected_home_goals >= 0),
    expected_away_goals double precision check (expected_away_goals is null or expected_away_goals >= 0),
    expected_total_goals double precision check (expected_total_goals is null or expected_total_goals >= 0),
    over_2_5_probability double precision check (over_2_5_probability is null or over_2_5_probability between 0 and 1),
    under_2_5_probability double precision check (under_2_5_probability is null or under_2_5_probability between 0 and 1),
    btts_yes_probability double precision check (btts_yes_probability is null or btts_yes_probability between 0 and 1),
    btts_no_probability double precision check (btts_no_probability is null or btts_no_probability between 0 and 1),
    top_score text,
    top_score_probability double precision check (top_score_probability is null or top_score_probability between 0 and 1),
    model_1x2_version text,
    model_1x2_sha256 text,
    model_goals_version text,
    model_goals_sha256 text,
    publisher_version text not null default 'product-publisher.v1',
    created_at timestamptz not null default now(),
    constraint product_prediction_snapshots_run_fixture_unique
        unique (run_id, league, home_team_model, away_team_model, commence_time_utc)
);

create index if not exists product_prediction_snapshots_kickoff_idx
    on public.product_prediction_snapshots (commence_time_utc);

create index if not exists product_prediction_snapshots_event_latest_idx
    on public.product_prediction_snapshots (event_id, generated_at_utc desc)
    where event_id is not null;

create index if not exists product_prediction_snapshots_fixture_latest_idx
    on public.product_prediction_snapshots (
        league,
        home_team_model,
        away_team_model,
        commence_time_utc,
        generated_at_utc desc
    );

alter table public.product_prediction_snapshots enable row level security;

create policy "service role inserts product prediction snapshots"
    on public.product_prediction_snapshots
    for insert
    to service_role
    with check (true);

create policy "service role reads product prediction snapshots"
    on public.product_prediction_snapshots
    for select
    to service_role
    using (true);
