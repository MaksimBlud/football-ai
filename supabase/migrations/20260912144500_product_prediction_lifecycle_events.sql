-- Append-only Product Prediction Lifecycle & Performance Ledger v1.
--
-- This table records immutable facts around already-persisted product
-- predictions. It is intentionally server-side only: no anon/authenticated
-- access and no UPDATE/DELETE privilege for service_role.

create table if not exists public.product_prediction_lifecycle_events (
    id bigint generated by default as identity primary key,
    lifecycle_schema_version text not null default 'product-lifecycle.v1',
    event_key text not null unique,
    event_type text not null check (
        event_type in ('PREDICTION_REGISTERED', 'MARKET_OBSERVED', 'SETTLED')
    ),
    product_match_id text not null,
    event_id text,
    league text not null,
    commence_time_utc timestamptz not null,
    home_team text not null,
    away_team text not null,
    source_prediction_snapshot_id bigint not null,
    source_prediction_run_id text,
    source_prediction_generated_at_utc timestamptz not null,
    source_prediction_created_at_utc timestamptz not null,
    source_odds_snapshot_id bigint,
    source_odds_snapshot_time_utc timestamptz,
    source_result_match_date date,
    source_result_persisted_at_utc timestamptz,
    recorded_at_utc timestamptz not null default now(),
    payload jsonb not null,
    constraint product_lifecycle_prediction_pre_kickoff
        check (source_prediction_created_at_utc < commence_time_utc),
    constraint product_lifecycle_market_not_post_kickoff
        check (
            source_odds_snapshot_time_utc is null
            or source_odds_snapshot_time_utc <= commence_time_utc
        )
);

create index if not exists product_lifecycle_match_time_idx
    on public.product_prediction_lifecycle_events
    (product_match_id, recorded_at_utc);

create index if not exists product_lifecycle_event_time_idx
    on public.product_prediction_lifecycle_events
    (event_id, recorded_at_utc)
    where event_id is not null;

create index if not exists product_lifecycle_type_time_idx
    on public.product_prediction_lifecycle_events
    (event_type, recorded_at_utc);

create index if not exists product_lifecycle_prediction_idx
    on public.product_prediction_lifecycle_events
    (source_prediction_snapshot_id, event_type);

alter table public.product_prediction_lifecycle_events enable row level security;

create policy "service role inserts product lifecycle events"
    on public.product_prediction_lifecycle_events
    for insert
    to service_role
    with check (true);

create policy "service role reads product lifecycle events"
    on public.product_prediction_lifecycle_events
    for select
    to service_role
    using (true);

revoke all privileges
    on table public.product_prediction_lifecycle_events
    from anon, authenticated;

revoke update, delete
    on table public.product_prediction_lifecycle_events
    from service_role;

grant select, insert
    on table public.product_prediction_lifecycle_events
    to service_role;

revoke all privileges
    on sequence public.product_prediction_lifecycle_events_id_seq
    from anon, authenticated;

grant usage, select
    on sequence public.product_prediction_lifecycle_events_id_seq
    to service_role;
